-- ──────────────────────────────────────────────────────────────────────────────
-- twilight.nvim
-- ------------------------------------------------------------------------------
-- Plugin que atenúa las porciones de código inactivas en Neovim, ayudando a
-- centrar la atención en la sección que estás editando. Ideal para mejorar la
-- concentración y reducir distracciones en archivos largos.
--
-- FUNCIONALIDAD:
--   • Dimmings dinámicos de código que no estás editando.
--   • Permite enfocarse en la porción activa del buffer.
--   • Compatible con diferentes esquemas de colores.
--   • Mejora la lectura y la concentración durante la programación.
--
-- CONFIGURACIÓN:
--   No requiere configuración básica para funcionar.
--   Opcionalmente se puede ajustar el número de líneas visibles, exclusiones
--   de filetypes o integración con otras herramientas.
--

