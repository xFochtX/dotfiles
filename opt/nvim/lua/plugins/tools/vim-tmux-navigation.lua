-- ──────────────────────────────────────────────────────────────────────────────
-- nvim-tmux-navigation
-- ------------------------------------------------------------------------------
-- Plugin que permite navegar de manera fluida entre paneles de Neovim y tmux.
-- Ideal para usuarios que trabajan en entornos divididos en múltiples ventanas
-- y desean moverse sin interrupciones entre ellas.
--
-- FUNCIONALIDAD:
--   • Navegación integrada entre Neovim y tmux usando los mismos atajos.
--   • Detecta automáticamente los límites de los paneles y cambia al siguiente.
--   • Compatible con splits verticales y horizontales.
--   • Facilita un flujo de trabajo más eficiente en entornos multipanel.
--
-- CONFIGURACIÓN:
--   No requiere configuración adicional para uso básico.
--   Puede extenderse mediante keymaps personalizados según necesidad.
--

